import { Router } from 'express';
import { uploadFile, parseText, getATSAnalysisController, optimizeATSController } from '../controllers/fileController';
import { generatePDFController } from '../controllers/pdfController';
import { checkATS } from '../controllers/atsController';
import { searchJobsHandler, extractFromUrlHandler, remoteJobsHandler } from '../controllers/jobsController';
import { generateCoverLetter } from '../controllers/coverLetterController';
import { polishResume } from '../controllers/resumePolishController';
import { trimToOnePage } from '../controllers/trimToOnePageController';
import { fixATS } from '../controllers/fixATSController';
import { analyzeSkillGap } from '../controllers/skillGapController';
import { generateInterviewPrep } from '../controllers/interviewPrepController';
import { startSimulation, getFeedback } from '../controllers/interviewSimulationController';
import { getSalaryInsights, compareSalaries } from '../controllers/salaryInsightsController';
import { generateCareerRoadmap } from '../controllers/careerRoadmapController';
import { tailorCV } from '../controllers/cvTailorController';
import { analyzeLinkedInProfile } from '../controllers/linkedinController';
import { optimizeKeywords } from '../controllers/keywordOptimizerController';
import { analyzeKeywordDensity } from '../controllers/keywordDensityController';
import { analyzeAttention } from '../controllers/attentionController';
import { generateBios } from '../controllers/bioGeneratorController';
import upload from '../middleware/multerConfig';
import { rateLimiter } from '../middleware/rateLimiter';
import { optionalAuth } from '../middleware/authMiddleware';
import { requireAiUser, requireAiQuota, validateAiInput } from '../middleware/aiAccess';

import { tailoringAccess, validateTailoringInput } from '../middleware/tailoringAccess';

import { cvImportSlots, receiveCVImport } from '../middleware/cvImportUpload';
import { importAndTailorCV } from '../controllers/cvImportTailorController';

const router = Router();

router.post('/file/upload', rateLimiter({ localCheckBypass: true, limit: 8, windowMs: 60000 }), requireAiUser, tailoringAccess.preflight, cvImportSlots, upload.single('file'), tailoringAccess.reserve, uploadFile);
router.post('/file/parse-text', rateLimiter({ localCheckBypass: true, limit: 8, windowMs: 60000 }), requireAiUser, (req, res, next) => { if (typeof req.body?.text !== 'string' || !req.body.text.trim() || req.body.text.length > 60000) { res.status(400).json({ message: 'Provide CV text of at most 60000 characters.' }); return; } next(); }, tailoringAccess.reserve, parseText);
router.post('/file/ats-score', getATSAnalysisController);
router.post('/file/ats-optimize', optimizeATSController);
router.post('/pdf/generate', rateLimiter({ limit: 6, windowMs: 60000 }), generatePDFController);
router.post('/ats/check', optionalAuth, rateLimiter({ localCheckBypass: true, limit: 1 }), upload.single('file'), checkATS);
router.post('/jobs/remote', rateLimiter({ limit: 6, windowMs: 60000 }), remoteJobsHandler);
router.post('/jobs/search', rateLimiter({ limit: 6, windowMs: 60000 }), searchJobsHandler);
router.post('/jobs/extract', rateLimiter({ limit: 6, windowMs: 60000 }), extractFromUrlHandler);
router.post('/cover-letter/generate', generateCoverLetter);
router.post('/resume/polish', polishResume);
router.post('/resume/trim-one-page', requireAiUser, validateAiInput('resume_trim'), requireAiQuota('resume_trim'), trimToOnePage);
router.post('/resume/fix-ats', requireAiUser, validateAiInput('ats_fix'), requireAiQuota('ats_fix'), fixATS);
router.post('/skills/gap', analyzeSkillGap);
router.post('/interview/prep', generateInterviewPrep);
router.post('/interview/simulate', startSimulation);
router.post('/interview/feedback', getFeedback);
router.post('/salary/insights', getSalaryInsights);
router.post('/salary/compare', compareSalaries);
router.post('/career/roadmap', generateCareerRoadmap);
router.get('/cv/tailor/allowance', rateLimiter({ localCheckBypass: true, limit: 30, windowMs: 60000, message: 'Please wait before checking usage again.' }), tailoringAccess.allowance);
router.post('/cv/import', rateLimiter({ localCheckBypass: true, limit: 8, windowMs: 60000, message: 'Please wait before importing again.' }), tailoringAccess.preflight, cvImportSlots, receiveCVImport, tailoringAccess.reserve, importAndTailorCV);
router.post('/cv/tailor/upload', rateLimiter({ localCheckBypass: true, limit: 8, windowMs: 60000, message: 'Please wait before importing again.' }), tailoringAccess.preflight, cvImportSlots, receiveCVImport, tailoringAccess.reserve, importAndTailorCV);
router.post('/cv/tailor', rateLimiter({ localCheckBypass: true, limit: 12, windowMs: 60000, message: 'Please wait before retrying tailoring.' }), validateTailoringInput, tailoringAccess.reserve, tailorCV);
router.post('/linkedin/analyze', upload.single('file'), analyzeLinkedInProfile);
router.post('/ats/keyword-optimize', optimizeKeywords);
router.post('/keyword/density', analyzeKeywordDensity);
router.post('/attention/analyze', optionalAuth, rateLimiter({ localCheckBypass: true, limit: 5 }), analyzeAttention);
router.post('/bios/generate', requireAiUser, validateAiInput('bios'), requireAiQuota('bios'), generateBios);

export default router;
