const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const names = ['20261014_cv_versions.sql','20261014_ai_feature_usage.sql','20261014_legacy_usage_alignment.sql'];
function buildMigrationBundle() {
  const blocks=names.map(name=>{
    const sql=fs.readFileSync(path.join(__dirname,'../migrations',name),'utf8').replace(/\r\n/g,'\n');
    const checksum=crypto.createHash('sha256').update(sql).digest('hex');
    const body=sql.split(/\r?\n/).filter(line=>!['BEGIN;','COMMIT;'].includes(line.trim())).join('\n');
    return `-- Source: ${name}\n-- SHA256: ${checksum}\n${body}`;
  });
  return '-- Generated by scripts/build-migration-bundle.cjs. Review before running in the production SQL editor.\n-- All changes share one transaction; any failure rolls the patch back.\nBEGIN;\n\n'+blocks.join('\n\n')+'\nCOMMIT;\n';
}
module.exports={buildMigrationBundle};
if(require.main===module){
  const output=path.join(__dirname,'../migrations/releases/20261014.sql');
  fs.mkdirSync(path.dirname(output),{recursive:true});
  fs.writeFileSync(output,buildMigrationBundle());
  console.log('Created migrations/releases/20261014.sql');
}
